; TVRAM1.COM - PC-98 テキスト VRAM 構造 測定プログラム
;
; 目的:
;   テキスト画面の VRAM に「直接」バイトを書き込み、どのセルに何が出るかを
;   観測して、以下を確定する。
;     (1) 文字コード面の先頭アドレス
;     (2) 1セルあたりのバイト数と、上位バイトの役割
;     (3) 行の間隔(何バイト進むと次の行か)と、画面の終端
;     (4) 全角文字の格納方法(バイト順と、右半分セルの印)
;     (5) 属性面の先頭アドレスと、各ビットの意味
;
; 測定方針:
;   「こうなっているはず」を書き込むのではなく、**判別できる配置**を書き込む。
;   例えば全角はバイト順の候補2通りを別々のセルに置き、どちらが読める字に
;   なるかで決める。外れたほうは化けるので、結果を見れば一意に決まる。
;
; 属性面の初期化について:
;   既定値を知らないまま定数で埋めると画面が消えることがある(表示ビットを
;   落とす等)。そのため cell 0 の現在値を読み、その値で埋める。
;   「今の画面で正常に見えている属性」を複製するので、前提を持ち込まない。
;
; 実行後:
;   キー入力待ちで停止する。COMMAND.COM のプロンプトが 0 行目を上書きして
;   測定結果を壊すのを避けるため。読み取りが済んでから任意のキーを送ること。
;
; ビルド: nasm -f bin TVRAM1.ASM -o TVRAM1.COM

        cpu     8086
        org     0x100

CHR_SEG equ     0xA000          ; 文字コード面(と仮定して測る)
ATR_SEG equ     0xA200          ; 属性面(と仮定して測る)
ROW     equ     160             ; 1行あたりのバイト数(と仮定して測る)

start:
        ; ---- [0] 属性面を「現在の cell 0 の値」で埋める ----
        mov     ax, ATR_SEG
        mov     es, ax
        mov     ax, [es:0]      ; 今の正常な属性値
        xor     di, di
        mov     cx, 2000        ; 2000 セル分
        rep     stosw

        ; ---- [1] 文字コード面を空白で埋める ----
        mov     ax, CHR_SEG
        mov     es, ax
        xor     di, di
        mov     ax, 0x0020      ; ' '
        mov     cx, 2000
        rep     stosw

        ; ---- [2] 位置の測定: 表から単発書き込み ----
        mov     si, ctab
.cloop:
        lodsw
        cmp     ax, 0xFFFF
        je      .cdone
        mov     di, ax
        lodsw
        mov     [es:di], ax
        jmp     .cloop
.cdone:

        ; ---- [3] 属性ビットの測定: 4行目に 'X' を32個 ----
        mov     di, 4*ROW
        mov     cx, 32
        mov     ax, 0x0058      ; 'X'
        rep     stosw

        ; ---- [4] 属性ビットの測定: 6行目に 'Y' を8個 ----
        mov     di, 6*ROW
        mov     cx, 8
        mov     ax, 0x0059      ; 'Y'
        rep     stosw

        ; ---- [5] 4行目の属性に 0x00..0x1F を1セルずつ ----
        mov     ax, ATR_SEG
        mov     es, ax
        mov     di, 4*ROW
        xor     ax, ax
        mov     cx, 32
.a1:
        mov     [es:di], ax
        add     di, 2
        inc     ax
        loop    .a1

        ; ---- [6] 6行目の属性に上位3ビットを振る((i<<5)|1) ----
        mov     di, 6*ROW
        mov     ax, 0x0001
        mov     cx, 8
.a2:
        mov     [es:di], ax
        add     di, 2
        add     ax, 0x0020
        loop    .a2

        ; ---- [7] キー待ち(画面を保持する) ----
        mov     ah, 0x07        ; 直接コンソール入力・エコー無し
        int     0x21

        mov     ax, 0x4C00
        int     0x21

; ---------------------------------------------------------------
; 書き込み表: dw オフセット, dw 書き込む16bit値 / 0xFFFF で終端
;
; 期待と、外れた場合に何が分かるか:
;   0x0000 'A' … 面の先頭。出なければ CHR_SEG が違う
;   0x0002 'B' … 1セル2バイトなら 'A' の右隣
;   0x0004 'C' … 上位バイト 0xFF。文字が化ければ上位バイトも文字コードの一部
;   0x009E 'D' … 行間隔160なら 0行目の右端(79桁目)
;   0x00A0 'E' … 行間隔160なら 1行目の左端
;   0x0F9E 'F' … 25x80 の最終セル(24行79桁)
;   0x0FA0 'G' … 25x80 の外。表示されれば画面は25行より広い
;   0x1000 'H' … 4096バイト目。別ページや折り返しの検出
;   0x1F9E 'I' … 8KBの終端付近
; 全角(「亜」= JIS 0x3021)のバイト順を2通り置く:
;   0x0010/0x0012 … 下位=0x21 上位=0x30、右半分は上位に 0x80 を足す
;   0x0018/0x001A … 下位=0x30 上位=0x21、右半分は下位に 0x80 を足す
;   0x0020        … 対になる右半分を書かない単独の全角コード
; ---------------------------------------------------------------
ctab:
        dw      0x0000, 0x0041          ; 'A'
        dw      0x0002, 0x0042          ; 'B'
        dw      0x0004, 0xFF43          ; 'C' + 上位0xFF
        dw      0x009E, 0x0044          ; 'D'
        dw      0x00A0, 0x0045          ; 'E'
        dw      0x0F9E, 0x0046          ; 'F'
        dw      0x0FA0, 0x0047          ; 'G'
        dw      0x1000, 0x0048          ; 'H'
        dw      0x1F9E, 0x0049          ; 'I'
        dw      0x0010, 0x3021          ; 全角候補A 左half
        dw      0x0012, 0xB021          ; 全角候補A 右half(上位に0x80)
        dw      0x0018, 0x2130          ; 全角候補B 左half
        dw      0x001A, 0x21B0          ; 全角候補B 右half(下位に0x80)
        dw      0x0020, 0x3021          ; 対無しの全角コード
        dw      0xFFFF
